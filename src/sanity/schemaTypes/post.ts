import { defineArrayMember, defineField, defineType } from 'sanity';

export const post = defineType({
	name: 'post',
	title: 'Article',
	type: 'document',
	groups: [
		{ name: 'content', title: 'Content', default: true },
		{ name: 'details', title: 'Details' },
		{ name: 'review', title: 'Review & sources' },
		{ name: 'seo', title: 'SEO & sharing' },
	],
	fields: [
		defineField({
			name: 'title',
			title: 'Title',
			type: 'string',
			group: 'content',
			validation: (rule) => rule.required().min(10).max(110),
		}),
		defineField({
			name: 'slug',
			title: 'URL slug',
			type: 'slug',
			group: 'content',
			description: 'Click "Generate" to create it from the title. Each article needs a unique slug.',
			options: { source: 'title', maxLength: 96 },
			validation: (rule) => rule.required(),
		}),
		defineField({
			name: 'excerpt',
			title: 'Short excerpt',
			type: 'text',
			rows: 3,
			group: 'content',
			description: 'One or two sentences shown on article cards.',
			validation: (rule) => rule.required().max(220),
		}),
		defineField({
			name: 'mainImage',
			title: 'Featured image',
			type: 'image',
			group: 'content',
			options: { hotspot: true },
			fields: [
				defineField({
					name: 'alt',
					title: 'Alternative text',
					type: 'string',
					description: 'Describe the image for people who cannot see it.',
					validation: (rule) => rule.required(),
				}),
			],
			validation: (rule) => rule.required(),
		}),
		defineField({
			name: 'body',
			title: 'Article content',
			type: 'blockContent',
			group: 'content',
			validation: (rule) => rule.required(),
		}),
		defineField({
			name: 'faqs',
			title: 'FAQ section (optional)',
			type: 'array',
			group: 'content',
			of: [
				defineArrayMember({
					type: 'object',
					name: 'faq',
					fields: [
						defineField({
							name: 'question',
							type: 'string',
							validation: (rule) => rule.required(),
						}),
						defineField({
							name: 'answer',
							type: 'text',
							rows: 4,
							validation: (rule) => rule.required(),
						}),
					],
					preview: { select: { title: 'question', subtitle: 'answer' } },
				}),
			],
		}),
		defineField({
			name: 'author',
			title: 'Author',
			type: 'reference',
			group: 'details',
			to: [{ type: 'author' }],
		}),
		defineField({
			name: 'category',
			title: 'Category',
			type: 'reference',
			group: 'details',
			to: [{ type: 'category' }],
			validation: (rule) => rule.required(),
		}),
		defineField({
			name: 'tags',
			title: 'Tags',
			type: 'array',
			group: 'details',
			of: [defineArrayMember({ type: 'string' })],
			options: { layout: 'tags' },
		}),
		defineField({
			name: 'publishedAt',
			title: 'Publication date',
			type: 'datetime',
			group: 'details',
			initialValue: () => new Date().toISOString(),
			validation: (rule) => rule.required(),
		}),
		defineField({
			name: 'updatedAt',
			title: 'Last updated',
			type: 'datetime',
			group: 'details',
			description: 'Set this when you make a meaningful change to the article.',
		}),
		defineField({
			name: 'featured',
			title: 'Feature this article',
			type: 'boolean',
			group: 'details',
			initialValue: false,
			description: 'The most recent featured article is shown at the top of the blog.',
		}),
		defineField({
			name: 'relatedPosts',
			title: 'Related articles (optional)',
			type: 'array',
			group: 'details',
			of: [defineArrayMember({ type: 'reference', to: [{ type: 'post' }] })],
			validation: (rule) => rule.max(3).unique(),
		}),
		defineField({
			name: 'isPlaceholder',
			title: 'Demonstration content',
			type: 'boolean',
			group: 'details',
			initialValue: false,
			description:
				'Shows a notice on the article saying it is sample content awaiting review. Switch off once the article is reviewed.',
		}),
		defineField({
			name: 'reviewedBy',
			title: 'Clinically reviewed by',
			type: 'reference',
			group: 'review',
			to: [{ type: 'author' }],
			description: 'Only set this once a qualified professional has actually reviewed the article.',
		}),
		defineField({
			name: 'reviewedAt',
			title: 'Review date',
			type: 'date',
			group: 'review',
			hidden: ({ document }) => !document?.reviewedBy,
		}),
		defineField({
			name: 'sources',
			title: 'Sources',
			type: 'array',
			group: 'review',
			description: 'Reputable sources that support health information in this article.',
			of: [
				defineArrayMember({
					type: 'object',
					name: 'source',
					fields: [
						defineField({
							name: 'title',
							type: 'string',
							validation: (rule) => rule.required(),
						}),
						defineField({
							name: 'url',
							type: 'url',
							validation: (rule) => rule.uri({ scheme: ['http', 'https'] }),
						}),
					],
				}),
			],
		}),
		defineField({
			name: 'seo',
			title: 'SEO',
			type: 'object',
			group: 'seo',
			options: { collapsible: false },
			fields: [
				defineField({
					name: 'title',
					title: 'SEO title',
					type: 'string',
					description: 'Leave empty to use the article title. Aim for under 60 characters.',
					validation: (rule) => rule.max(70).warning('Long titles may be cut off in search results.'),
				}),
				defineField({
					name: 'description',
					title: 'Meta description',
					type: 'text',
					rows: 3,
					description: 'Leave empty to use the excerpt. Aim for 120–160 characters.',
					validation: (rule) =>
						rule.max(170).warning('Long descriptions may be cut off in search results.'),
				}),
				defineField({
					name: 'ogImage',
					title: 'Social sharing image',
					type: 'image',
					description: 'Optional. Defaults to the featured image. Ideal size 1200 × 630.',
				}),
				defineField({
					name: 'noIndex',
					title: 'Hide from search engines',
					type: 'boolean',
					initialValue: false,
				}),
			],
		}),
	],
	orderings: [
		{
			title: 'Publication date, newest first',
			name: 'publishedAtDesc',
			by: [{ field: 'publishedAt', direction: 'desc' }],
		},
	],
	preview: {
		select: {
			title: 'title',
			category: 'category.title',
			media: 'mainImage',
			placeholder: 'isPlaceholder',
		},
		prepare: ({ title, category, media, placeholder }) => ({
			title,
			subtitle: [placeholder ? 'Demo' : null, category].filter(Boolean).join(' · '),
			media,
		}),
	},
});
